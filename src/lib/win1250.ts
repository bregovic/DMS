const REV = new Map<number, number>();
for (const [byte, cp] of Object.entries(HIGH)) REV.set(cp, Number(byte));

export function encodeWin1250(str: string): Uint8Array {
  const out = new Uint8Array(str.length);
  for (let i = 0; i < str.length; i++) {
    const code = str.charCodeAt(i);
    if (code <= 0x7f) out[i] = code;
    else out[i] = REV.get(code) ?? 0x3f; // „?" pro znaky mimo CP1250
  }
  return out;
}

/** CSV řetězec → base64 bajtů ve Windows-1250 (pro přenos ze server action do klienta). */
export function csvToWin1250Base64(csv: string): string {
  return Buffer.from(encodeWin1250(csv)).toString("base64");
}
